# -*- coding: utf-8 -*-
"""技术瓶颈的定量刻画：状态空间内的可辨识性"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np
from lib_sim import load, parse_ids, features

d = load(); kind, sigma, seed = parse_ids(d["ids"])
L = []; A = L.append

A("=" * 76)
A("一、现象：同一工况内 P1—Q 关系无法辨识，跨工况才能辨识")
A("=" * 76)
iN = int(np.where((kind == "normal") & (sigma == 0.3))[0][0])
o = d["obs"][iN]
A("normal|0.3 首条轨迹的工况结构（B 阀 180—299 开）：")
for lab, lo, hi in [("B关 早期", 20, 175), ("B开", 200, 299), ("B关 后期", 305, 599)]:
    P1 = o[lo:hi, 1]; Q = o[lo:hi, 2]
    A("  %-10s  t=%d—%d  P1 均值 %.2f 标准差 %.3f（相对 %.2f%%）  Q 均值 %.4f 标准差 %.4f" % (
        lab, lo, hi - 1, P1.mean(), P1.std(), P1.std() / P1.mean() * 100, Q.mean(), Q.std()))
A("")
A("⇒ 每个工况内 P1 只波动约 1%%，跨度极小。")
A("⇒ 在这样窄的范围内，log-log 斜率由噪声主导 → 拟合指数不可信（实测得 -1.46 到 +0.49）")
A("")

A("=" * 76)
A("二、根因：可辨识性 —— 两种物理解释在数学上不可分")
A("=" * 76)
A("在本项目的测点上，观测方程可写成：")
A("    P1 = Ps − Rc·Q² − R·Q²          （串联阻力）")
A("    Q  = C·√P1                        （负载关系）")
A("")
A("展开参数化：  P1 = Ps − (Rc + R)·C²·P1")
A("             ⇒ P1·(1 + (Rc+R)·C²) = Ps")
A("             ⇒ P1 = Ps / (1 + (Rc+R)·C²)")
A("             ⇒ Q  = C·√Ps / √(1 + (Rc+R)·C²)")
A("")
A("关键：联合量 β = (Rc + R)·C² 一个标量决定一切。")
A("⇒ 在单一工况下，只能辨识 β，无法把 Rc、R、C 分离。")
A("⇒ 实测印证：Q/√P1 全程恒为 0.280（即 C 已知），")
A("   而 R 与 Rc 的具体分配不可辨识 —— 这正是 (P0−P1)/Q² 中 Rc 成分的来源。")
A("")

A("=" * 76)
A("三、定量：需要多大的压力跨度才能辨识指数？")
A("=" * 76)
A("设真实 Q = C·√P1，在 [P1_lo, P1_hi] 范围内拟合 Q = a·P1^n")
A("拟合斜率 n 的相对误差与压力跨度 ΔP/P 的关系：")
A("   斜率不确定性 ≈ σ_Q/(Q·√N) / ln(P1_hi/P1_lo)")
A("")
A("  P1跨度(相对)   ln比值   σ_Q/Q=0.1%时 n 的不确定度   σ_Q/Q=1%时")
for rng in [0.01, 0.02, 0.05, 0.10, 0.20, 0.50, 1.00]:
    lr = np.log(1 + rng)
    for sq in [0.001, 0.01]:
        pass
    u1 = 0.001 / lr if lr > 0 else float("inf")
    u2 = 0.01 / lr if lr > 0 else float("inf")
    A("  %8.0f%%  %7.4f  %22.4f  %14.4f" % (rng * 100, lr, u1, u2))
A("")
A("⇒ 当前台架在单一供压档下 P1 跨度约 1%% → n 的不确定度高达 1.0—10（毫无意义）")
A("⇒ 要辨识到 n 的不确定度 ≤0.05，需压力跨度 ≥20%%（σ_Q/Q=0.1%%）")
A("⇒ 这正是申报书设计『80/120/160kPa 三档供压』的意义 —— 跨档合起来跨度 ~100%%，")
A("   实测跨档拟合得 n=0.49（正确），单档拟合得 −1.46（错误）")
A("")

A("=" * 76)
A("四、由此定位的三个技术瓶颈（项目要回答的核心问题）")
A("=" * 76)
A("瓶颈一【可辨识性】")
A("  在单一工况点、仅有 ±1%% 压力波动时，压力—流量关系不可辨识。")
A("  → 必须用『多供压档 + 阀态变化』构造足够宽的跨度。")
A("  → 问题：跨度要多大才够？（本节给出 20%% 的初步答案，台架需验证）")
A("")
A("瓶颈二【共模/差模不可分】")
A("  β = (Rc+R)·C² 把上游共同阻力 Rc 与本支管阻力 R 混在一起。")
A("  → 单支管 + 单点流量无法把『上游供压变化』与『本支管故障』分开。")
A("  → 这是结构性限制，不是算法能解决的；必须靠『干管参照』或『阀态分档』。")
A("  → 问题：加一路干管参照后，可分的边界在哪？")
A("")
A("瓶颈三【切换与故障的时域可分性】")
A("  实测：B 阀开关使 P0 从 116.6 骤降到 104.1（−10.7%%），P1 从 109.9 降到 98.2，")
A("        但 C 恒为 0.280、R 恒为 0.79 —— 切换只是换了一个工况点，不是故障。")
A("  → 切换的特征是『阶跃 + 新稳态』；故障的特征是『同一工况内参数漂移』。")
A("  → 问题：能否用『参数在工况内的漂移』而非『参数绝对值』做判据？")
A("    （这正是本项目的判据新意所在：把判据建立在『与同工况健康参照的偏离』上，")
A("      而不是绝对阈值上）")
A("")

A("=" * 76)
A("五、实测印证：健康工况内的残差尺度有多大（决定可检下限）")
A("=" * 76)
mask = np.zeros(len(o), bool)
mask[20:176] = True
mask[300:600] = True
f = features(o)
v = mask & f["valid"]
P1s, Qs, Rs = f["p1"][v], f["q"][v], f["Rh"][v]
lg = np.polyfit(np.log(P1s / 100), np.log(Qs), 1)
n, a = lg[0], float(np.exp(lg[1]))
q_ref = a * (P1s / 100) ** n
gain = np.median(Qs / q_ref); r0 = np.median(Rs)
eq = Qs / (gain * q_ref) - 1; er = Rs - r0
sq = 1.4826 * np.median(np.abs(eq - np.median(eq)))
sr = 1.4826 * np.median(np.abs(er - np.median(er)))
A("用 B 阀『关』的工况（20—175 + 300—599）联合标定：")
A("  拟合指数 n = %+.4f     r0 = %.4f     增益 = %.4f" % (n, r0, gain))
A("  e_Q 的稳健尺度 s_Q = %.5f        e_R 的稳健尺度 s_R = %.5f" % (sq, sr))
A("")
A("原判据阈值：e_Q > %.2f, e_R > %.2f" % (0.06, 0.6))
A("⇒ 阈值 / 噪声尺度 = %.0f 倍（流量通道）、%.0f 倍（阻力通道）" % (0.06 / sq, 0.6 / sr))
A("")
A("结论：")
A("  · 阈值比健康噪声大 26—60 倍 → 正常工况几乎不可能误报（这是好的一面）")
A("  · 但也意味着：**只有幅度很大的故障才会被检出**")
A("  · 在 σ_p=0.3kPa（理想）下噪声尺度仅 0.0023；")
A("    若传感器不确定度升到 σ_p=10kPa，噪声尺度会等比放大 → 阈值不再有裕度")
A("  · ⇒ **可检下限由测量不确定度决定**，这正是本项目要建立『可检边界』的原因")
outdir = os.path.join(os.path.dirname(os.path.abspath(__file__)), "results")
os.makedirs(outdir, exist_ok=True)
open(os.path.join(outdir, "identifiability.txt"), "w", encoding="utf-8").write("\n".join(L))
print("\n".join(L))
